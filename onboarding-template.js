// テキスト → { sections:[{id,title,notes:[],items:[{id,title,details:[]}]}], errors:[] }
// 項目IDは「章番号-項目番号」。記録は開始時に sections を写し取るので、
// ひな形を書き換えても作成済みの記録の項目IDとチェックはずれない。
export function parseTemplate(text) {
  const sections = [];
  const errors = [];
  let sec = null, item = null;
  String(text || '').split(/\r?\n/).forEach((raw, i) => {
    const line = raw.trim();
    if (!line) return;
    const ln = i + 1;
    if (line.startsWith('##')) {
      sec = { id: 's' + (sections.length + 1), title: line.replace(/^#+\s*/, ''), notes: [], items: [] };
      sections.push(sec);
      item = null;
    } else if (line.startsWith('□') || line.startsWith('☐')) {
      if (!sec) { errors.push(`${ln}行目：章（## で始まる行）より前に項目があります`); return; }
      item = { id: sec.id + '-' + (sec.items.length + 1), title: line.replace(/^[□☐]\s*/, ''), details: [] };
      sec.items.push(item);
    } else if (line.startsWith('└')) {
      if (!item) { errors.push(`${ln}行目：項目（□ で始まる行）より前に説明（└）があります`); return; }
      item.details.push(line.replace(/^└\s*/, ''));
    } else if (line.startsWith('※')) {
      if (!sec) { errors.push(`${ln}行目：章より前に注記（※）があります`); return; }
      sec.notes.push(line.replace(/^※\s*/, ''));
    } else {
      errors.push(`${ln}行目：行の先頭は「##」「□」「└」「※」のどれかにしてください（${line.slice(0, 20)}…）`);
    }
  });
  if (!sections.length) errors.push('章が1つもありません');
  sections.forEach(s => { if (!s.items.length) errors.push(`「${s.title}」に項目がありません`); });
  return { sections, errors };
}

// 事業所の担当業務（□ 項目／└ 説明 だけ。章は持たない）→ { items:[{title,details:[]}], errors:[] }
// R・A Fitness の手配、外出支援の準備など、担当になる人にだけ教える業務。
export function parseOfficeItems(text) {
  const items = [];
  const errors = [];
  let item = null;
  String(text || '').split(/\r?\n/).forEach((raw, i) => {
    const line = raw.trim();
    if (!line) return;
    const ln = i + 1;
    if (line.startsWith('□') || line.startsWith('☐')) {
      item = { title: line.replace(/^[□☐]\s*/, ''), details: [] };
      if (!item.title) { errors.push(`${ln}行目：業務名がありません`); return; }
      if (items.some(x => x.title === item.title)) errors.push(`${ln}行目：「${item.title}」が重複しています`);
      items.push(item);
    } else if (line.startsWith('└')) {
      if (!item) { errors.push(`${ln}行目：業務（□ で始まる行）より前に説明（└）があります`); return; }
      item.details.push(line.replace(/^└\s*/, ''));
    } else {
      errors.push(`${ln}行目：行の先頭は「□」「└」のどちらかにしてください（${line.slice(0, 20)}…）`);
    }
  });
  return { items, errors };
}

export function countItems(sections) {
  return (sections || []).reduce((n, s) => n + (s.items || []).length, 0);
}
